<h1 class="page-title page-title--left">A propos de Maison Rosalie</h1>

<section class="about">
    <p class="about__tagline">L'élégance du chocolat belge depuis 1928</p>
    <div class="about__text">
        <p>L'histoire de Maison Rosalie commence dans les années 1920,<br>dans une demeure discrète des environs de Bruxelles. Rosalie Janssens,<br>fille d'un horticulteur et passionnée de pâtisserie fine,<br>développe très tôt une fascination pour les arômes délicats du cacao,<br>alors encore considéré comme un produit rare et précieux.</p>
        <p>Inspirée par l'art de vivre belge et les grandes maisons européennes,<br>Rosalie imagine des chocolats conçus comme des bijoux gustatifs.</p>
    </div>
    <div class="about__text">
        <p>Chaque création doit allier la noblesse des matières premières,<br>la précision artisanale et une élégance intemporelle.</p>
        <p>En 1928, elle ouvre son premier atelier.<br>Derrière une façade sobre, elle confectionne à la main des pralinés raffinés,<br>des ganaches délicates et des tablettes aux recettes exclusives.<br>Sa réputation grandit rapidement auprès d'une clientèle exigeante :<br>artistes, diplomates et familles de la bourgeoisie belge.</p>
    </div>
    <div class="about__text about__text--wide">
        <p>Au fil des générations, Maison Rosalie demeure fidèle à l'héritage de sa fondatrice.<br>Les recettes historiques sont préservées tandis que de nouvelles créations enrichissent la collection.<br>Chaque chocolat est élaboré en petites séries, dans le respect des gestes<br>traditionnels et avec une sélection rigoureuse des meilleurs cacaos.</p>
        <p>Aujourd'hui, Maison Rosalie incarne l'alliance rare entre savoir-faire artisanal et luxe discret. Les coffrets, inspirés de l'élégance belge, renferment des créations pensées comme des moments de dégustation d'exception.</p>
    </div>
